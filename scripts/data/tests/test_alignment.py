import importlib
import hashlib
import json
import subprocess
import sys
from pathlib import Path
import tempfile
import unittest

import h5py
import numpy as np
from fixtures import make_dataset


class AlignmentAuditTests(unittest.TestCase):
    def test_reconstruction_excludes_cross_episode_and_terminal_actions(self):
        self.assertTrue(Path('scripts/data/audit_alignment.py').exists(), 'Alignment audit not implemented')
        audit = importlib.import_module('scripts.data.audit_alignment')
        with tempfile.TemporaryDirectory() as temp:
            path = make_dataset(Path(temp) / 'two-episodes.h5', (3, 3))
            # Recorded source data, not values generated by the audit/controller.
            initial = [423., 182., 192.67061, 335.15677, 2.9476998, 0., 0.]
            following = [427.1394, 174.6082, 192.67061, 335.15677, 2.9476998, 52.380672, -93.53691]
            with h5py.File(path, 'a') as f:
                third = [430.44006, 169.26328, 192.67061, 335.15677, 2.9476998, 21.584066, -31.594496]
                state = np.array([initial, following, third, initial, following, third], dtype=np.float32)
                f['state'][:] = state
                f['proprio'][:] = state[:, [0, 1, 5, 6]]
                # Large terminal actions must not affect reconstruction.
                f['action'][:] = [[.14, -.25], [.05860596, -.086082], [999, 999]] * 2
            result = audit.audit_alignment(path, code_revision='synthetic-reviewed')
            self.assertEqual(result['lags']['0']['count'], 4)
            self.assertLess(result['lags']['0']['max_pixels'], 1e-4)
            self.assertEqual(result['lags']['-1']['count'], 2)
            self.assertEqual(result['lags']['1']['count'], 2)
            self.assertTrue(result['proprio_matches_state_0_1_5_6'])
            self.assertEqual(result['status'], 'passed')
            self.assertEqual(result['code_revision'], 'synthetic-reviewed')
            self.assertEqual(result['source']['hdf5_sha256'], hashlib.sha256(path.read_bytes()).hexdigest())
            self.assertEqual(result['source']['hdf5_size_bytes'], path.stat().st_size)

    def test_cli_marks_bad_dynamics_failed_and_exits_nonzero(self):
        with tempfile.TemporaryDirectory() as temp:
            path = make_dataset(Path(temp) / 'bad.h5', (2, 2))
            output = Path(temp) / 'audit.json'
            completed = subprocess.run([
                sys.executable, '-m', 'scripts.data.audit_alignment', '--hdf5', str(path), '--output', str(output), '--code-revision', 'synthetic-reviewed',
            ], capture_output=True, text=True)
            self.assertNotEqual(completed.returncode, 0)
            report = json.loads(output.read_text())
            self.assertEqual(report['status'], 'failed')
            self.assertFalse(report['checks']['lag0_position_within_tolerance'])
            self.assertEqual(report['thresholds']['max_position_error_pixels'], 1e-4)
            self.assertEqual(report['source']['hdf5_sha256'], hashlib.sha256(path.read_bytes()).hexdigest())

    def test_zero_motion_without_lag_discrimination_does_not_pass(self):
        audit = importlib.import_module('scripts.data.audit_alignment')
        with tempfile.TemporaryDirectory() as temp:
            path = make_dataset(Path(temp) / 'ambiguous.h5', (4,))
            with h5py.File(path, 'a') as f:
                f['state'][:] = 0
                f['proprio'][:] = 0
                f['action'][:] = 0
            result = audit.audit_alignment(path, code_revision='synthetic-reviewed')
            self.assertEqual(result['status'], 'failed')
            self.assertFalse(result['checks']['lag0_far_below_shifted'])
